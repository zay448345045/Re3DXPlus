"""Read the arcade's dress-up parts (ghost battle, "TG") tables out of `main` (under the
unicorn x86 emulator) and write src/dressdb.h.

usage: dressdb.py <main>

- get_tb_level_parts(gem, level) 0x88e5748: the part each dress-up level 1..63 gives,
  {kind, number}; kinds 0 wheel, 1 aero set, 2 bonnet, 3 wing, 4 aero mirror, 5 sticker,
  6 straight neon, 8 spot neon, 9 nothing (the gem cars' empty levels).
- get_parts_data(kind, number, 0, gem) 0x88e60c4: +0x18 the part's name picture (the GET
  screen's 0x1f7c), +0x14 its picture (the bonnet, wing and mirror GET screen's 0xd3c). Its sprintf (plt 0x8422a18) and printf (0x8422238) are stubbed out.
- clSeqTgPartsGetAeroThread::run 0x886a0bc: the GET screen's level digits (0x9408a80) and
  its kind titles (0x9408ac0).
- the wheels the levels give (kind 0: the number is an emTireModelID) and their other colours:
  their wheel_list.lua name (nsCarParts::LuaWheelNickNameGetFromWheelModelID 0x893d7d8) and
  the index of their texture set (WheelTextureIDGetFromWheelModelID 0x893d944).
- the wheel change screen's (clSeqTgChangePartsWheelThread): by wheel won its maker (the
  ladder row's third field), its colours (WheelModelIDMemberGetFromWheelModelID 0x893dfb8,
  the gem cars' 1, at most 6) and by colour get_parts_data(0, wheel, colour, gem): + 8 the
  tyre model worn, + 4 the swatch, + 0x24 the big picture; colour 0's + 0x10 the bar's
  picture and + 0x1c the name logo.
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from cardb import Main  # noqa: E402

m = Main(sys.argv[1])
m.mu.mem_write(0x8422A18, b"\xc3")
m.mu.mem_write(0x8422238, b"\xc3")
m.mu.mem_map(0x30000000, 0x100000)  # (scratch the calls may touch)

rows = {}
makers = {}
for gem in (0, 1):
    for lv in range(1, 64):
        p = m.call(0x88E5748, gem, lv) & 0xFFFFFFFF
        kind, num = m.r32(p), m.r32(p + 4)
        d = m.call(0x88E60C4, kind, num, 0, gem) & 0xFFFFFFFF
        rows[gem, lv] = (kind, num, m.r32(d + 0x18), m.r32(d + 0x14))
        if kind == 0:
            makers[gem, lv] = m.r32(p + 8)

digits = [m.r32(0x9408A80 + 4 * i) for i in range(10)]
titles = [m.r32(0x9408AC0 + 4 * i) for i in range(9)]

out = ["/* Generated by tools/dressdb.py from the arcade's dress-up tables: do not edit. */",
       "#ifndef DRESSDB_H", "#define DRESSDB_H", "",
       "/* by gem car (get_car_model_data + 0x28) and dress-up level 1..63: the part it gives",
       " * {kind, number, name picture, picture}; kind 1 is an aero set (number 1..3: A, B, C) */",
       "static const short DRESS_LADDER[2][64][4] = {"]
for gem in (0, 1):
    out.append("  {")
    out.append("    { -1, 0, 0, 0 },")
    for lv in range(1, 64):
        out.append("    { %d, %d, %d, %d }," % rows[gem, lv])
    out.append("  },")
out += ["};", "",
        "/* the wheels the levels give, by emTireModelID: their wheel_list.lua name and texture",
        " * set (tools/stage/pack_cars.py --wheels packs each as data/wheels/<name>_<set>.wpk) */",
        "/* menu3d: its GET screen model (get_parts_data + 0xc, data/menu3d/wheel/<menu3d>.igb;",
        " * pack_cars.py --wheels packs it as data/wheels/<menu3d>.wpk) */",
        "typedef struct {", "  short model, set;", "  const char *name, *menu3d;", "} dress_wheel;",
        "static const dress_wheel DRESS_WHEELS[] = {"]
heads = []
for (gem, lv), r in sorted(rows.items()):
    if r[0] != 0:
        continue
    num = r[1]
    n = 1 if gem else max(1, min(6, m.call(0x893DFB8, num)))
    cols = []
    for j in range(n):
        d = m.call(0x88E60C4, 0, num, j, gem) & 0xFFFFFFFF
        cols.append((m.r32(d + 8), m.r32(d + 4), m.r32(d + 0x24)))
    d = m.call(0x88E60C4, 0, num, 0, gem) & 0xFFFFFFFF
    heads.append((num, gem, makers[gem, lv], n, m.r32(d + 0x10), m.r32(d + 0x1C), cols))
wheels = {}
for num, gem, mk, n, bar, logo, cols in heads:
    d = m.call(0x88E60C4, 0, num, 0, gem) & 0xFFFFFFFF
    menu3d = m.cstr(m.r32(d + 0xC)).rsplit("/", 1)[-1].rsplit(".", 1)[0]
    for mid, _, _ in cols:
        # (the other colours share the GET screen's model of the one won)
        wheels.setdefault(mid, (m.call(0x893D944, mid), m.cstr(m.call(0x893D7D8, mid) & 0xFFFFFFFF), menu3d))
for mid in sorted(wheels):
    out.append('  { %d, %d, "%s", "%s" },' % ((mid,) + wheels[mid]))
out += ["};", "",
        "/* the wheel change screen's (clSeqTgChangePartsWheelThread): by wheel won (head, gem) its",
        " * maker (0 Yokohama, 1 Watanabe, 2 Rays, 3 Enkei, 4 the gem cars'), colours n, the bar's",
        " * picture and the name logo; by colour the tyre model, the swatch and the big picture */",
        "typedef struct {", "  short head, gem, maker, n, bar, logo;", "  short model[6], swatch[6], pic[6];",
        "} dress_wheel_set;", "static const dress_wheel_set DRESS_WHEEL_SETS[] = {"]
for num, gem, mk, n, bar, logo, cols in heads:
    pad = lambda k: ", ".join(str(c[k]) for c in cols) + ", 0" * (6 - n)
    out.append("  { %d, %d, %d, %d, %d, %d, { %s }, { %s }, { %s } }," % (num, gem, mk, n, bar, logo, pad(0), pad(1), pad(2)))
out += ["};", "",
        "/* the GET screen's level digits (menu_p_t_tuning_title_0..9) and kind titles */",
        "static const short DRESS_DIGIT[10] = { %s };" % ", ".join(map(str, digits)),
        "static const short DRESS_KIND_TITLE[9] = { %s };" % ", ".join(map(str, titles)),
        "", "#endif", ""]
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "dressdb.h"), "w").write("\n".join(out))
