"""Read the player's name entry (seqCardNameSelect, clSeqCardNameSelectThread) tables out of
`main` and write src/namedb.h.

usage: namedb.py <main>

- The card keeps its name as five bytes, each a character of GetCardNameChar2Wchar's table
  (0x932a440, 256 wchar_t; GetWchar2CardNameChar takes the first match back).
- clSeqCardNameSelectThread::run copies the grid (0x93f7ca0: 5 pages of 3 rows of 20, each
  an 8-byte wchar string) and its columns' x (0x93f7b60); the rows' y are 0x109, 0x129, 0x149.
  Page 0 (the digits) is the target search's; the name takes pages 1..4 (katakana, hiragana,
  capitals, small letters). A string's U+042E (and the hiragana page's ＿ there) is the space
  key, ← the back space; ゛ and ゜ turn the character before into its voiced form (the table
  0x93f8600), here by the characters' own decompositions.
"""
import os
import struct
import sys
import unicodedata

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import menupack as M  # noqa: E402

e = M.Elf(sys.argv[1])
chars = M.name_chars(e)
index = {}
for k, c in enumerate(chars):
    index.setdefault(c, k)
SPACE, UNDER = index[chr(0x3000)], index[chr(0xff3f)]
BS, DAKU, HANDAKU = -2, -3, -4

grid = []
for page in range(1, 5):
    row = []
    for i in range(60):
        c = chr(struct.unpack_from("<I", e.d, e.off(0x93F7CA0 + 8 * (60 * page + i)))[0])
        if c == chr(0x2190):
            row.append(BS)
        elif c == chr(0x309b):
            row.append(DAKU)
        elif c == chr(0x309c):
            row.append(HANDAKU)
        elif c == chr(0x42e) or (c == chr(0xff3f) and page <= 2):
            row.append(SPACE if page <= 2 else UNDER)
        elif c == chr(0xff0d) and page <= 2:
            row.append(index[chr(0x30fc)])  # the kana pages' long vowel mark
        else:
            row.append(index.get(c, -1))
            if row[-1] < 0:
                print("not on the card:", hex(ord(c)))
    grid.append(row)

voiced = []
for c in chars:
    v = []
    for mark in (chr(0x3099), chr(0x309a)):
        f = unicodedata.normalize("NFC", c + mark)
        v.append(index.get(f, -1) if len(f) == 1 else -1)
    voiced.append(v)

xs = struct.unpack_from("<20i", e.d, e.off(0x93F7B60))
out = ["/* Generated by tools/namedb.py from the arcade's name entry: do not edit. */",
       "#ifndef NAMEDB_H", "#define NAMEDB_H", "",
       "/* the card's name characters (GetCardNameChar2Wchar) */",
       "#define NAMEDB_N %d" % len(chars),
       "static const unsigned short NAMEDB_WCHAR[NAMEDB_N] = {"]
for k in range(0, len(chars), 16):
    out.append("  " + " ".join("0x%04x," % ord(c) for c in chars[k:k + 16]))
out += ["};", "#define NAMEDB_SPACE %d" % SPACE,
        "/* the grid's keys: back space, " + chr(0x309b) + " and " + chr(0x309c) + " (font 8's NAMEDB_N and NAMEDB_N + 1 are the back",
        " * space's and the space's marks) */",
        "#define NAMEDB_BS %d" % BS, "#define NAMEDB_DAKU %d" % DAKU, "#define NAMEDB_HANDAKU %d" % HANDAKU,
        "#define NAMEDB_DAKU_MARK %d" % index[chr(0x309b)], "#define NAMEDB_HANDAKU_MARK %d" % index[chr(0x309c)],
        "/* katakana, hiragana, capitals, small letters: 3 rows of 20 */",
        "static const short NAMEDB_GRID[4][60] = {"]
for row in grid:
    out.append("  { %s }," % ", ".join(str(v) for v in row))
out += ["};", "static const short NAMEDB_GRID_X[20] = { %s };" % ", ".join(str(x) for x in xs),
        "static const short NAMEDB_GRID_Y[3] = { 265, 297, 329 };",
        "/* each character's voiced (" + chr(0x309b) + ") and semi-voiced (" + chr(0x309c) + ") form, -1 none */",
        "static const short NAMEDB_VOICED[NAMEDB_N][2] = {"]
for k in range(0, len(chars), 8):
    out.append("  " + " ".join("{ %d, %d }," % tuple(v) for v in voiced[k:k + 8]))
out += ["};", "", "#endif", ""]
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "namedb.h"), "w").write("\n".join(out))
