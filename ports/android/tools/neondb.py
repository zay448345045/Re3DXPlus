"""Read where each car's under neon goes out of `main` by running the arcade's own lookups
under the unicorn emulator, and write src/neondb.h.

usage: neondb.py <main>   (WMMT_MAIN for tools/recomp/x86emu.py)

- clNeon::setup (0x895094c) loads the neon's model (data/effect/car_neon_<colour>_race.igb,
  car_spotneon_..., by neon 1..12: the table at 0x9420960) and gives it its own matrix:
  makeScale(nsNeonData::NeonScaleGetFromCarId(car, body)) (0x858d2a8) with the translation
  nsNeonData::NeonOffsetGetFromCarId(car, body) (0x858d3d4); a car not in their table (0x97faa00,
  56 rows of 0x64 bytes: the car, then by body 0..3 {offset, scale}, which the static
  initialiser 0x858a310 fills) takes the vector at 0x980c470 for both.
- The car (emCarID) of a pack: tools/brakelamps.json's (brakelampdb.py).

Output: NEON_PLACE[CARDB_NPACKS][4] {offset x y z, scale x y z} by CARDB_PACKS and body
(0 stock, 1..3 aero A..C).
"""
import json
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "recomp"))
os.environ["WMMT_MAIN"] = sys.argv[1]
from unicorn.x86_const import UC_X86_REG_EAX, UC_X86_REG_EDX  # noqa: E402
from x86emu import Emu  # noqa: E402

STATIC_INIT = 0x858a310
SCALE = 0x858d2a8
OFFSET = 0x858d3d4

e = Emu(trace_unknown=False)
e.uc.reg_write(UC_X86_REG_EAX, 1)
e.uc.reg_write(UC_X86_REG_EDX, 0xffff)
e.call(STATIC_INIT)
out = e.alloc(16)


def vec(fn, car, body):
    e.call(fn, out, car, body)
    return struct.unpack("<3f", e.rd(out, 12))


def cf(v):
    t = "%g" % round(v, 4)
    return (t if "." in t else t + ".0") + "f"


cardb = open(os.path.join(HERE, "..", "src", "cardb.h")).read()
packs = re.findall(r'"([^"]+)"', cardb[cardb.index("CARDB_PACKS["):cardb.index("};", cardb.index("CARDB_PACKS["))])
cars = {k.lower(): v for k, v in json.load(open(os.path.join(HERE, "brakelamps.json")))["cars"].items()}

lines = ["/* Generated by tools/neondb.py from the arcade's nsNeonData tables: do not edit. */",
         "#ifndef NEONDB_H", "#define NEONDB_H", "",
         "/* by CARDB_PACKS and body (0 stock, 1..3 aero A..C): the under neon's offset (x y z) and",
         " * scale (x y z) in the car's space (nsNeonData::NeonOffsetGetFromCarId, NeonScaleGetFromCarId) */",
         "static const float NEON_PLACE[%d][4][6] = {" % len(packs)]
for p in packs:
    car = cars[p.lower()]
    rows = []
    for body in range(4):
        o, s = vec(OFFSET, car, body), vec(SCALE, car, body)
        rows.append("{ " + ", ".join(cf(v) for v in o + s) + " }")
    lines.append("  { %s }, /* %s (car %d) */" % (", ".join(rows), p, car))
lines += ["};", "", "#endif", ""]
open(os.path.join(HERE, "..", "src", "neondb.h"), "w").write("\n".join(lines))
