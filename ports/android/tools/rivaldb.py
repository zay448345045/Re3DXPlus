"""Read the story mode's rivals out of `main` (clEffStoryType's table at 0x973a5c0, 0x158 bytes
per story select) by running its own lookups under the unicorn emulator, and write
src/rivaldb.h.

usage: rivaldb.py <main>   (WMMT_MAIN for tools/recomp/x86emu.py)

- A select's periods (getPeriodMax 0x857dc04) are movies and races (isRace 0x857dde4); each
  race has its series (getESeries 0x857d8f0) and up to 3 rivals: clEffStoryType::
  getECarType(period, i) 0x857e08c, getChara(period, i) 0x857d494 and getCar(i) 0x857daac
  (the rival's own car model, emCarModelID 247..302, named by the table at 0x9777880:
  CHARA_NIS_S30_AKIO, ...). 13 selects have two races (select 0: series 24 against Akio's
  Z31, then 25 against the Z31 and the Blackbird); 53 put two or three rivals on the road.
- The select number is what clRaceThread::initStory hands SConfigPlay +0x38 (the level
  CRivalSetting::GetSettingPt gets).
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "recomp"))
os.environ["WMMT_MAIN"] = sys.argv[1]
from x86emu import Emu  # noqa: E402

e = Emu(trace_unknown=False)
obj = e.alloc(0x40)
rows = []
for sel in range(200):
    e.w32(obj, sel)
    head = [e.u32(0x973a5c0 + 0x158 * sel + 4 * k) for k in range(3)]
    if not 0 < head[0] < 400:
        break
    race = 0
    for period in range(e.call(0x857dc04, obj)):
        if not e.call(0x857dde4, obj, period) & 0xff:
            continue
        series = e.call(0x857d8f0, obj, period)
        for i in range(3):
            ct = e.call(0x857e08c, obj, period, i)
            if ct in (0, 0xffffffff):
                continue
            ch = e.call(0x857d494, obj, period, i)
            model = e.call(0x857daac, obj, i)
            name = e.cstr(e.u32(0x9777880 + 4 * model)) if model < 400 else "?"
            rows.append((sel, race, i, ch, ct, model, name, series))
        race += 1
# the rivals' own models: data/characar/<folder>, CHARA_<FOLDER> in the model table (two
# names differ from their folders), packed by tools/stage/pack_cars.py --chara into data/chara
ALIAS = {"TOY_KZH100G_GACHAN": "TOY_KZH100_GACHAN", "TOY_UCF10_GACCHAN": "TOY_UCF10_GACHAN"}
folders = {f.upper(): f for f in os.listdir(sys.argv[2])} if len(sys.argv) > 2 else {}
chara = []
for r in rows:
    key = r[6][len("CHARA_"):] if r[6].startswith("CHARA_") else ""
    f = folders.get(ALIAS.get(key, key))
    if f and f not in chara:
        chara.append(f)
    if not f:
        print("no characar folder for", r[6])
rows = [r[:7] + (chara.index(f) if (f := folders.get(ALIAS.get(r[6][6:], r[6][6:]))) else -1, r[7]) for r in rows]
here = os.path.dirname(os.path.abspath(__file__))
out = ["/* Generated by tools/rivaldb.py from the arcade's story mode data: do not edit. */",
       "#ifndef RIVALDB_H", "#define RIVALDB_H", "",
       "typedef struct {",
       "  int select;        /* the story select (SConfigPlay +0x38) */",
       "  int race, slot;    /* its race (0 the first) and the rival's place in that race */",
       "  int character;     /* ECharacter */",
       "  int type;          /* ECarType */",
       "  int model;         /* the rival's own car model (emCarModelID) */",
       "  const char *name;  /* its name in the arcade's model table */",
       "  int chara;         /* its model in RIVALDB_CHARA (data/chara/<folder>.wpk), -1 none */",
       "  int series;        /* the race (ESeries: GetConfigRaceField_Story) */",
       "} rivaldb_rival;", "",
       "#define RIVALDB_N %d" % len(rows),
       "static const rivaldb_rival RIVALDB[RIVALDB_N] = {"]
out += ['  { %d, %d, %d, %d, %d, %d, "%s", %d, %d },' % r for r in rows]
out += ["};", "", "#define RIVALDB_NCHARA %d" % len(chara), "static const char *const RIVALDB_CHARA[RIVALDB_NCHARA] = {"]
out += ['  "%s",' % f for f in chara]
out += ["};", "", "#endif", ""]
open(os.path.join(here, "..", "src", "rivaldb.h"), "w").write("\n".join(out))
print(len(rows), "rivals in", rows[-1][0] + 1, "story selects")
