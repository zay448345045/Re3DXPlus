"""Read every car's engine sound set out of `main` and write src/sounddb.h.

usage: sounddb.py <main>

- nsAudio::GetEngineTypeFromCarType (0x85388f8): the table at 0x931c0a0 (46 x {ECarType,
  sound type by tuning stage[4]}). The stage: yt::CSeq::Init loads the engine with the
  car's power tune, at least 4 (CSE::Mc_Load), capped at 10, as the row's first int of the
  table at 0x931bf40 (24-byte rows: stage 2 for 4..7, 3 for 8..10). So a stock car
  (power 0) sounds as stage 2, one tuned past power 7 as stage 3, the last.
- clAudioDataManage::GetTypeDescPtr: 0x931c520 + 32 t, shorts: +4 the engine waves[4],
  +18 the muffler waves[4] (wave table 0x931e380, 12 bytes: +8 the file name).
- GetEngineDescPtr / GetMufflerDescPtr: 0x931d720 / 0x931cac0 + 70 t, 10 bytes a layer:
  the rpm bands engine_calc and muffler_calc fade the layers by (r0, r1, base, r2, r3).
"""
import os
import struct
import sys

CAR_TYPES = 0x931C0A0
TYPE_DESC = 0x931C520
WAVES = 0x931E380
ENGINE_BANDS = 0x931D720
MUFFLER_BANDS = 0x931CAC0
STOCK, FULL_TUNE = 2, 3


class Elf:
    def __init__(self, path):
        self.b = open(path, "rb").read()
        shoff, = struct.unpack_from("<I", self.b, 0x20)
        se, sn = struct.unpack_from("<HH", self.b, 0x2E)
        self.secs = [struct.unpack_from("<10I", self.b, shoff + i * se) for i in range(sn)]

    def off(self, va):
        for s in self.secs:
            if s[3] and s[1] != 8 and s[3] <= va < s[3] + s[5]:
                return va - s[3] + s[4]
        raise ValueError(hex(va))

    def read(self, fmt, va):
        return struct.unpack_from(fmt, self.b, self.off(va))

    def cstr(self, va):
        o = self.off(va)
        return self.b[o:self.b.index(b"\0", o)].decode()


def main():
    e = Elf(sys.argv[1])
    by_car, by_car_stock = {}, {}
    for i in range(46):
        row = e.read("<5i", CAR_TYPES + 20 * i)
        by_car.setdefault(row[0], row[1 + FULL_TUNE])
        by_car_stock.setdefault(row[0], row[1 + STOCK])
    sets = sorted(set(by_car.values()) | set(by_car_stock.values()))

    def wave(i):
        return os.path.basename(e.cstr(e.read("<I", WAVES + 12 * i + 8)[0]))[:-4]

    h = ["/* Generated by tools/sounddb.py from the arcade's nsAudio tables: do not edit. */",
         "#ifndef SOUNDDB_H", "#define SOUNDDB_H", "",
         "/* A layer's rpm band: fades in over r0..r1, out over r2..r3; plays at its recorded",
         " * pitch at base. */",
         "typedef struct { short r0, r1, base, r2, r3; } sounddb_band;", "",
         "/* An engine sound set: four engine and four muffler loops (data/sound/engine). */",
         "typedef struct {",
         "  const char *engine[4], *muffler[4];",
         "  sounddb_band engine_bands[4], muffler_bands[4];",
         "} sounddb_set;", "",
         "#define SOUNDDB_NSETS %d" % len(sets),
         "static const sounddb_set SOUNDDB_SETS[SOUNDDB_NSETS] = {"]
    for t in sets:
        d = e.read("<16h", TYPE_DESC + 32 * t)
        eng, muf = [wave(x) for x in d[2:6]], [wave(x) for x in d[9:13]]
        bands = [["{ %d, %d, %d, %d, %d }" % e.read("<5h", base + 70 * t + 10 * b) for b in range(4)]
                 for base in (ENGINE_BANDS, MUFFLER_BANDS)]
        h.append("  { { %s }, { %s },  /* sound type %d */" % (", ".join('"%s"' % w for w in eng),
                                                              ", ".join('"%s"' % w for w in muf), t))
        h.append("    { %s },\n    { %s } }," % (", ".join(bands[0]), ", ".join(bands[1])))
    h.append("};")
    h.append("")
    n = max(by_car) + 1
    h.append("/* by ECarType (car_spec.type): fully tuned (power 8 and up), and stock */")
    h.append("#define SOUNDDB_NTYPES %d" % n)
    for name, table in (("SOUNDDB_BY_TYPE", by_car), ("SOUNDDB_BY_TYPE_STOCK", by_car_stock)):
        h.append("static const unsigned char %s[SOUNDDB_NTYPES] = {" % name)
        row = [str(sets.index(table[c])) if c in table else "0" for c in range(n)]
        for i in range(0, n, 16):
            h.append("  " + ", ".join(row[i:i + 16]) + ",")
        h.append("};")
    h += ["", "#endif", ""]
    here = os.path.dirname(os.path.abspath(__file__))
    open(f"{here}/../src/sounddb.h", "w").write("\n".join(h))
    print("%d car types, %d sound sets" % (len(by_car), len(sets)))


if __name__ == "__main__":
    main()
