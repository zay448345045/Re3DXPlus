"""Read the story's tuning work (seqStTuneEff 0x883f7c0, clSeqStTuneEffThread) tables out of
`main` and write src/steff.h and tools/steff_texts.txt.

usage: steff.py <main>

- clArg (0x8846640): T = power + handling after the tuning; the row by T and the side tuned:
  T <= 20 handling (handling - 1: 0x93fd780, the UCF10's 0x93fd820) or power (power - 1:
  0x93fd8c0; power 1 of an NA car 0x93fd960, of the R2 0x93fd970), T 21..30 (T - 21:
  0x93fd640, the UCF10's 0x93fd6e0), past 30 0x93fd980. A row is 16 bytes {top bar title,
  part picture (1 none), install anime, car pose}, its two lines 8 bytes on (0x9776720,
  0x9776780, 0x97767e0, 0x9776830, 0x9776838, 0x9776660, 0x97766c0; none past 30).
- the car's flags (nsStTune isCarGemballa, isCarHighAce, isCarHiliftHighAce, isCarNA,
  isCarR2, isCarUCF10; get_car_model_data(model) + 0x18 == 0x120f, 0x1212, 0x1211) and the
  tuner of steps 21..30 and 31.. (getCarTuneCharaU30, U33) for the complete picture.
- the car's poses (0x97fefc0: [2][8] {position, rotation in degrees}, set by the static
  initialiser) and the tuners'
  complete pictures (0x93fd5e0).
The lines (clSpriteFont, font 1, two lines) are pre-rendered by menupack.py as STEFF_TEXT + k.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from cardb import Main  # noqa: E402

TEXT_BASE = 105500
m = Main(sys.argv[1])


def u(a):
    return m.r32(a)


def ws(a):
    s = []
    while a and u(a):
        s.append(chr(u(a)))
        a += 4
    return "".join(s)


texts = []
TABLES = [("HAND", 0x93fd780, 0x9776720, 10), ("HAND_UCF10", 0x93fd820, 0x9776780, 10),
          ("POWER", 0x93fd8c0, 0x97767e0, 10), ("POWER_NA", 0x93fd960, 0x9776830, 1),
          ("POWER_R2", 0x93fd970, 0x9776838, 1), ("MID", 0x93fd640, 0x9776660, 10),
          ("MID_UCF10", 0x93fd6e0, 0x97766c0, 10), ("TOP", 0x93fd980, 0, 1)]
out = ["/* Generated by tools/steff.py from the arcade's story tuning work (seqStTuneEff): do not edit. */",
       "#ifndef STEFF_H", "#define STEFF_H", "",
       "#define STEFF_TEXT %d /* the pre-rendered lines: STEFF_TEXT + k (menupack.py) */" % TEXT_BASE,
       "#define STEFF_ANIM 0x232 /* the install animes' first id (menu_layout_st_install_front_a) */", "",
       "/* a row: the top bar's title, the part's picture (1 none), the install anime (by id), the",
       " * car's pose, the lines (-1 none) */",
       "typedef struct { short title, parts, anim, pose, text; } steff_row;"]
for name, base, txt, n in TABLES:
    rows = []
    for k in range(n):
        t, p, a, pose = (u(base + 16 * k + 4 * i) for i in range(4))
        x = -1
        if txt:
            lines = [ws(u(txt + 8 * k)), ws(u(txt + 8 * k + 4))]
            x = len(texts)
            texts.append(lines)
        rows.append("{ %d, %d, 0x%x, %d, %d }" % (t, p, a, pose, x))
    out.append("static const steff_row STEFF_%s[%d] = { %s };" % (name, n, ", ".join(rows)))

# filled by the file's static initialiser (not in the file's data): its values
POSE0 = [(0, 7.4, -35, 0, 0, 0), (0.3, 0.5, 0, 0, 39, 0), (0, 0.5, 0, 0, 90, 0), (-1.4, 0.5, 0, 0, 144, 0),
         (0, 7.4, -35, 0, 180, 0), (-1.0, 0.5, 0, 0, 215, 0), (0, 0.5, 0, 0, 267, 0), (-1.3, 0.5, 0, 0, 325, 0)]
POSE1 = [(0, 1.8, 1.7, 0, 0, 0)] + POSE0[1:4] + [(0, 1.8, 1.7, 0, 180, 0)] + POSE0[5:]
poses = ["{ %s }" % ", ".join("%.1ff" % v for v in p) for p in POSE0 + POSE1]
out += ["/* the car's poses (0x97fefc0): before (0) and after (1) the work, {position, rotation in degrees} */",
        "static const float STEFF_POSE[2][8][6] = {",
        "  { %s }," % ", ".join(poses[:8]), "  { %s }," % ", ".join(poses[8:]), "};",
        "/* the tuners' complete pictures (0x93fd5e0, 1 none) */",
        "static const short STEFF_COMPLETE[17] = { %s };" % ", ".join(str(u(0x93fd5e0 + 4 * k)) for k in range(17))]

cars = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "cars.json")))
flags = []
for mk in cars["makers"]:
    row_ = []
    for car in mk["cars"]:
        cid = m.call(0x893DD48, car["colors"][0]["model"], 1)
        model = m.call(0x893CF98, cid, 1)
        k18 = m.r32(m.call(0x88DC0C8, model) + 0x18)
        b = [m.call(a, cid) & 0xff for a in (0x8832aec, 0x8832a00, 0x8832a1c, 0x8832a2c, 0x8832ac0, 0x8832ad0)]
        row_.append("{ %s }" % ", ".join(str(v) for v in b + [int(k18 == 0x120f), int(k18 == 0x1212), int(k18 == 0x1211),
                                                               m.call(0x8832b2c, cid), m.call(0x8832ba4, cid)]))
    flags.append(row_)
out += ["/* by the car select's cars (src/cardb.h): gemballa, HighAce, HiliftHighAce, NA, R2, UCF10, the",
        " * model's +0x18 0x120f, 0x1212, 0x1211, the tuner of steps 21..30 and 31.. */",
        "typedef struct { unsigned char gem, hiace, hilift, na, r2, ucf10, m0f, m12, m11, u30, u33; } steff_car;",
        "static const steff_car STEFF_CAR[%d][%d] = {" % (len(flags), max(len(r) for r in flags))]
out += ["  { %s }," % ", ".join(r) for r in flags]
out += ["};", "", "#endif", ""]
here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, "..", "src", "steff.h"), "w").write("\n".join(out))
open(os.path.join(here, "steff_texts.txt"), "w", encoding="utf-8").write(
    "".join("1\t%s\t%s\n" % tuple(t) for t in texts))
print(len(texts), "texts")
