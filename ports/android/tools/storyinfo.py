"""Read what the story race's rival boxes show (clStoryConsole's clRivalInfoConsole) out of
`main` and write src/storyinfo.h.

usage: storyinfo.py <main>   (WMMT_MAIN for tools/recomp/x86emu.py)

clStoryConsole::update (0x85c8008) gives the boxes, in order, the race's rivals i (< getCarCount
(period) 0x857d6f4) whose character (getChara(period, i) 0x857d494) is no irregular one
(nsMenuCheck::checkSrotyIrregularRival 0x86336e8, checkStoryIrregularRival(chara, period)
0x8633798) while clWorkSpace::getInfoStoryCharacterEnable(i) holds: the box's face, name and
car pictures are getStCharData(chara) 0x857cef4's (0x9739300, 20 bytes: ECharacter, face,
name, car, wide; 240 of them, the first when it is not there), its x by which of the 3 are wide
(0x93cf1c0: 8 x 3 ints, index 4 wide0 + 2 wide1 + wide2), y 76; the advantage as the
10-in-a-row's (getInfoStoryAdvantage(i), mm).
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "recomp"))
os.environ["WMMT_MAIN"] = sys.argv[1]
from x86emu import Emu  # noqa: E402

e = Emu(trace_unknown=False)
obj = e.alloc(0x40)
shown = []  # in tools/rivaldb.py's order (src/rivaldb.h's RIVALDB)
for sel in range(200):
    e.w32(obj, sel)
    if not 0 < e.u32(0x973a5c0 + 0x158 * sel) < 400:
        break
    for period in range(e.call(0x857dc04, obj)):
        if not e.call(0x857dde4, obj, period) & 0xff:
            continue
        count = e.call(0x857d6f4, obj, period)
        for i in range(3):
            ct = e.call(0x857e08c, obj, period, i)
            if ct in (0, 0xffffffff):
                continue
            ch = e.call(0x857d494, obj, period, i)
            odd = e.call(0x86336e8, ch) & 0xff or e.call(0x8633798, ch, period) & 0xff
            shown.append(int(i < count and not odd))
chars = []
for k in range(240):
    chars.append(tuple(e.u32(0x9739300 + 20 * k + 4 * j) for j in range(5)))
xs = [e.u32(0x93cf1c0 + 4 * k) for k in range(24)]

out = ["/* Generated by tools/storyinfo.py from the arcade's clStoryConsole: do not edit. */",
       "#ifndef STORYINFO_H", "#define STORYINFO_H", "",
       "/* getStCharData's: a character's (ECharacter) face, name and car pictures, wide box */",
       "typedef struct { short chara, face, name, car, wide; } storyinfo_char;",
       "#define STORYINFO_NCHAR %d" % len(chars),
       "static const storyinfo_char STORYINFO_CHAR[STORYINFO_NCHAR] = {"]
out += ["  { %d, %d, %d, %d, %d }," % c for c in chars]
out += ["};", "/* by src/rivaldb.h's row: whether the rival gets a box (0: irregular, or past getCarCount) */",
        "static const unsigned char STORYINFO_SHOWN[%d] = {" % len(shown)]
out += ["  " + ", ".join(str(s) for s in shown[k:k + 32]) + "," for k in range(0, len(shown), 32)]
out += ["};", "/* the boxes' x (640 wide) by which are wide: [4 wide0 + 2 wide1 + wide2][box] */",
        "static const short STORYINFO_X[8][3] = {"]
out += ["  { %d, %d, %d }," % tuple(xs[3 * k:3 * k + 3]) for k in range(8)]
out += ["};", "", "#endif", ""]
here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, "..", "src", "storyinfo.h"), "w").write("\n".join(out))
print(len(shown), "rivals,", sum(shown), "shown;", sum(1 for c in chars if c[4]), "wide")
