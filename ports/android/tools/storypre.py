"""Read the story race title page's pictures (clSeqStEnemyInformationThread, its constructor
at 0x883bd98) out of `main` and write src/storypre.h.

usage: storypre.py <main>   (WMMT_MAIN for tools/recomp/x86emu.py)

For each story select (clEffStoryType's index, src/rivaldb.h's select), a player who has not
cleared the story yet (clV386CardData::getStoryClearLoop 0):
- get_story_image_data(loop, getStorySelectInLoop) 0x8835624: {?, ?, picture, title} for the
  templates 0x1e10 and 0x1295 of menu_layout_pre_st;
- getCarForLoad(0..2) 0x857da1c through nsMenuCheck::getStCharCarImage 0x86334c0: the three
  rivals' car pictures for 0x1e0d..0x1e0f;
- getRamp 0x857d048 -> getRampImageIdx 0x8633320 -> getRampImageBg(idx, night) 0x8633380 for
  menu_g_pre_bg's template 0xb2f, getRampImageStoryInfo(idx) 0x86333a4 for 0x15f1;
- the episode number, loop * 100 + select in loop + 1, in the digits at 0x93fd3e0 (templates
  0x1d1d.. right to left of the five places, the unused ones hidden) and 0xdb0 (WA).
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "recomp"))
os.environ["WMMT_MAIN"] = sys.argv[1]
from x86emu import Emu  # noqa: E402

e = Emu(trace_unknown=False)
obj = e.alloc(0x40)
buf = e.alloc(0x40)
rows = []
for sel in range(200):
    if not 0 < e.u32(0x973a5c0 + 0x158 * sel) < 400:
        break
    e.w32(obj, sel)
    inloop = e.call(0x857ced4, obj)
    e.call(0x8835624, buf, 0, inloop)
    img = [e.u32(buf + 4 * k) for k in range(4)]
    cars = [e.call(0x86334c0, e.call(0x857da1c, obj, k)) for k in range(3)]
    ramp = e.call(0x8633320, e.call(0x857d048, obj))
    bg = [e.call(0x8633380, ramp, z) for z in range(2)]
    info = e.call(0x86333a4, ramp)
    rows.append((sel, inloop + 1, img[2], img[3], cars, bg, info))
digits = [e.u32(0x93fd3e0 + 4 * d) for d in range(10)]
out = ["/* Generated by tools/storypre.py from the arcade's story race title page: do not edit. */",
       "#ifndef STORYPRE_H", "#define STORYPRE_H", "",
       "typedef struct {",
       "  int episode;      /* the number before WA */",
       "  int picture, title; /* for menu_layout_pre_st's templates 0x1e10 and 0x1295 */",
       "  int cars[3];      /* the rivals' car pictures (0x1e0d..0x1e0f), 1 = none */",
       "  int bg[2];        /* menu_g_pre_bg's background (0xb2f), morning and night */",
       "  int info;         /* the ramp's story info (0x15f1) */",
       "} storypre_select;", "",
       "#define STORYPRE_N %d" % len(rows),
       "static const storypre_select STORYPRE[STORYPRE_N] = {"]
for r in rows:
    out.append("  { %d, %d, %d, { %d, %d, %d }, { %d, %d }, %d }," % (r[1], r[2], r[3], *r[4], *r[5], r[6]))
out += ["};", "",
        "static const int STORYPRE_DIGIT[10] = { %s };" % ", ".join(map(str, digits)),
        "", "#endif", ""]
here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, "..", "src", "storypre.h"), "w").write("\n".join(out))
print(len(rows), "selects; first", rows[0], "last", rows[-1], "digits", digits)
