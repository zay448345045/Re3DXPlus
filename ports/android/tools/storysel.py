"""Read the story's level and rival select (seqStEnemyLevelSelect, clThread_5_2_EnemySelect)
tables out of `main` and write src/storysel.h.

usage: storysel.py <main>

- get_story_image_data 0x8835624: 16-byte rows at 0x93fc920 by story index, {stage picture,
  its grey, the title page's picture, its title}; the selects take the first two.
- clSeqStEnemyLevelSelectThread::clMenuSelect: the levels' names, 4 a division (D =
  getStoryClearDivCount % 5) at 0x93fd040, and for a later loop's first division the
  tuner's story's two (0x4e7, 0x4e8) in place of the first two.
- clThread_5_2_EnemySelect::run: the chapter titles (char *, 0x93fd340, by index / 5; the
  later loops' first ten from entry 20) and the start ramps (0x93fd2e0) by the story index's
  entry of 0x93fd120 (from entry 100 for those first ten), drawn with clSpriteFont: menupack.py
  pre-renders them as STORYSEL_TEXT + k.
"""
import os
import struct
import sys


class Elf:
    def __init__(self, path):
        self.d = open(path, "rb").read()
        phoff, = struct.unpack_from("<I", self.d, 28)
        phnum, = struct.unpack_from("<H", self.d, 44)
        self.segs = []
        for i in range(phnum):
            t, off, va, _, fsz = struct.unpack_from("<5I", self.d, phoff + 32 * i)
            if t == 1:
                self.segs.append((va, off, fsz))

    def off(self, va):
        for v, o, n in self.segs:
            if v <= va < v + n:
                return o + va - v
        raise ValueError(hex(va))

    def u32(self, va):
        return struct.unpack_from("<I", self.d, self.off(va))[0]

    def cstr(self, va):
        o = self.off(va)
        return self.d[o:self.d.index(b"\0", o)].decode("utf-8")


elf = Elf(sys.argv[1])
images = [(elf.u32(0x93FC920 + 16 * i), elf.u32(0x93FC924 + 16 * i)) for i in range(111)]
levels = [elf.u32(0x93FD040 + 4 * i) for i in range(20)]
titles = [elf.cstr(elf.u32(0x93FD340 + 4 * i)) for i in range(22)]
ramps = [elf.cstr(elf.u32(0x93FD2E0 + 4 * i)) for i in range(17)]
ramp_of = [elf.u32(0x93FD120 + 4 * i) for i in range(110)]

out = ["/* Generated by tools/storysel.py from the arcade's story level and rival select: do not edit. */",
       "#ifndef STORYSEL_H", "#define STORYSEL_H", "",
       "/* by story index (get_story_image_data): the stage picture and its grey */",
       "static const int STORYSEL_IMAGE[111][2] = {"]
out += ["  { %d, %d }," % r for r in images]
out += ["};", "", "/* the levels' names by division and level; a later loop's first division has the tuner's story's for the first two */",
        "static const int STORYSEL_LEVEL[5][4] = {"]
out += ["  { %s }," % ", ".join(str(v) for v in levels[4 * d:4 * d + 4]) for d in range(5)]
out += ["};", "static const int STORYSEL_TUNER[2] = { 0x4e7, 0x4e8 };", "",
        "/* pre-rendered texts (menupack.py): the chapter titles 0..21, START RAMP, the ramps */",
        "#define STORYSEL_TEXT 101200",
        "#define STORYSEL_N_TITLES %d" % len(titles),
        "#define STORYSEL_START_RAMP (STORYSEL_TEXT + %d)" % len(titles),
        "#define STORYSEL_RAMP_TEXT (STORYSEL_TEXT + %d)" % (len(titles) + 1),
        "/* the start ramp (STORYSEL_RAMP_TEXT + k) by story index, the later loops' first ten from 100 */",
        "static const unsigned char STORYSEL_RAMP[110] = {"]
for i in range(0, 110, 20):
    out.append("  " + " ".join("%d," % v for v in ramp_of[i:i + 20]))
out += ["};", "", "#endif", ""]
here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, "..", "src", "storysel.h"), "w").write("\n".join(out))
# the texts, for menupack.py
open(os.path.join(here, "storysel_texts.txt"), "w", encoding="utf-8").write(
    "\n".join(["4\t" + t for t in titles] + ["1\tスタートランプ"] + ["4\t" + r for r in ramps]) + "\n")
print(len(images), "images,", len(titles), "titles,", len(ramps), "ramps")
