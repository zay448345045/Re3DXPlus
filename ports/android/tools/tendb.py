"""Read the 10-in-a-row mode's (TenFight, 十番勝負 / "OR") tables out of `main` and
data/carconfig/ytConfigTenFight.txt, and write src/tendb.h.

usage: tendb.py <main> <ytConfigTenFight.txt>

- Rivals: CRivalSetting::GetTenFightCharIndex(level, i) (0x89c0528) reads CharacterSet10 of
  the config (levels 1..10, ten characters each); the 32-man level (10) runs characters
  0..31 in order. GetTenFightCarType (0x89c065c) is the table 0x9778fc0[character], the
  character's model (getTenCharaCar 0x857f124) the table 0x9333660 (24 bytes a character,
  +0 emCarModelID, named by 0x9777880: CHARA_<FOLDER> as in src/rivaldb.h).
- clThread_7_3_LoadDisp (the race's title page, menu_layout_pre_or): per course in menu
  order and level the table 0x940d420 (16 bytes: the background 0xb2f, the course's name
  0x1b9a, the time zone 0x15ed and the start ramp 0x1870) and the level's 0x940d3e0 (0x186f).
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import menupack as M  # noqa: E402

e = M.Elf(sys.argv[1])
text = open(sys.argv[2], encoding="cp932", errors="replace").read()
block = text.split("CharacterSet10", 1)[1].split("LevelCurve10", 1)[0]
sets = []
for line in block.splitlines():
    line = line.split("//")[0]
    nums = [int(x) for x in re.findall(r"\d+", line)]
    if nums:
        sets.append(nums)
assert len(sets) == 10 and all(len(s) == 10 for s in sets), sets
sets.append(list(range(32)))

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
here = os.path.dirname(os.path.abspath(__file__))
rdb = open(os.path.join(here, "..", "src", "rivaldb.h")).read()
chara = re.findall(r'^  "([^"]+)",$', rdb.split("RIVALDB_CHARA[RIVALDB_NCHARA]", 1)[1], re.M)
upper = {c.upper(): i for i, c in enumerate(chara)}
ALIAS = {"TOY_KZH100G_GACHAN": "TOY_KZH100_GACHAN", "TOY_UCF10_GACCHAN": "TOY_UCF10_GACHAN"}  # as rivaldb.py
chars = []
for c in range(32):
    model = e.u32(0x9333660 + 24 * c)
    name = e.cstr(e.u32(0x9777880 + 4 * model))
    ctype = e.u32(0x9778fc0 + 4 * c)
    chars.append((ctype, model, name, upper.get(ALIAS.get(name[6:], name[6:]), -1)))
    if chars[-1][3] < 0:
        print("no chara pack for", c, name)

out = ["/* Generated by tools/tendb.py from the arcade's 10-in-a-row data: do not edit. */",
       "#ifndef TENDB_H", "#define TENDB_H", "",
       "/* the characters (ECharacter order of AllCharacterType): ECarType, model, its",
       " * RIVALDB_CHARA pack (-1: none packed, drawn as the car select's model of its type) */",
       "typedef struct { int type, model; const char *name; int chara; } tendb_char;",
       "#define TENDB_NCHAR 32",
       "static const tendb_char TENDB_CHAR[TENDB_NCHAR] = {"]
out += ['  { %d, %d, "%s", %d },' % ch for ch in chars]
out += ["};", "", "/* the rivals of each level (10: the 32-man extend), in order */",
        "#define TENDB_LEVELS 11", "static const int TENDB_RIVALS[TENDB_LEVELS] = { %s };" % ", ".join(str(len(s)) for s in sets),
        "static const signed char TENDB_SET[TENDB_LEVELS][32] = {"]
out += ["  { %s }," % ", ".join(str(x) for x in s) for s in sets]
out += ["};", "", "/* menu_layout_pre_or by menu order and level: background, course name, time zone, ramp */",
        "static const int TENDB_PRE[10][TENDB_LEVELS][4] = {"]
for o in range(10):
    out.append("  { %s }," % ", ".join("{ %s }" % ", ".join(str(e.u32(0x940d420 + 176 * o + 16 * l + 4 * k)) for k in range(4)) for l in range(11)))
out += ["};", "static const int TENDB_PRE_LV[TENDB_LEVELS] = { %s };" % ", ".join(str(e.u32(0x940d3e0 + 4 * l)) for l in range(11)),
        "", "#endif", ""]
open(os.path.join(here, "..", "src", "tendb.h"), "w").write("\n".join(out))
