"""Read the wall sparks' random directions out of `main` and write src/sparkdb.h.

usage: sparkdb.py <main>

- clCarSparkManager::createSpark (0x85f4eb0) takes spark i's random vector from table i % 4
  (pointers at 0x93d86c0, 100 igVec3f each, components -1..1) at a running index (0x97fda24)
  shared by all, which goes back to 0 after 99.
"""
import struct
import sys

d = open(sys.argv[1], "rb").read()
e_phoff, = struct.unpack_from("<I", d, 0x1c)
e_phnum, = struct.unpack_from("<H", d, 0x2c)
segs = []
for i in range(e_phnum):
    p_type, p_off, p_va, _, p_filesz = struct.unpack_from("<5I", d, e_phoff + 32 * i)
    if p_type == 1:
        segs.append((p_va, p_off, p_filesz))


def off(va):
    for s_va, s_off, size in segs:
        if s_va <= va < s_va + size:
            return va - s_va + s_off
    raise ValueError(hex(va))


tables = [struct.unpack_from("<I", d, off(0x93D86C0 + 4 * t))[0] for t in range(4)]
with open("src/sparkdb.h", "w") as fp:
    fp.write("/* Generated by tools/sparkdb.py from the arcade's clCarSparkManager tables: do not edit. */\n")
    fp.write("#ifndef SPARKDB_H\n#define SPARKDB_H\n\n")
    fp.write("/* createSpark's random vectors (components -1..1): 4 tables (0x93d86c0) of 100 */\n")
    fp.write("static const float SPARK_RAND[4][100][3] = {\n")
    for t in tables:
        v = struct.unpack_from("<300f", d, off(t))
        fp.write("  {\n")
        for k in range(100):
            fp.write("    { %s },\n" % ", ".join("%.9gf" % x if "." in "%.9g" % x or "e" in "%.9g" % x else "%.9g.0f" % x for x in v[3 * k:3 * k + 3]))
        fp.write("  },\n")
    fp.write("};\n\n#endif\n")
