"""Which city's map each story race runs on, for src/storycity.h.

A story race's start is its series' RaceField in data/carconfig/ytConfigStory.txt
(CConfigLoader::GetStorySeries): "ESeries_<name>" blocks, the line after "RaceField" naming
the series and the start ramp (ByRamp: HkBack, NgR_Marunouchi, Os..., WgIn_Daikoku) or area
(ByArea: KgAirport_In, TkC1_In). The ESeries numbers are the places of the names in
GetESeries_FromName's table (0x9777d80). The ramp or area name's prefix gives the city:
Hk Hakone, Ng/Nk Nagoya, Os Osaka, Fk Fukuoka, the rest (C1, N9, Wg, Kg, Tk) Tokyo's map.

usage: storycity.py <main> <ytConfigStory.txt>
"""
import os
import re
import struct
import sys

NAMES = 0x9777d80
CITY = {"Hk": "CAR_HAKONE", "Ng": "CAR_NAGOYA", "Nk": "CAR_NAGOYA", "Os": "CAR_OSAKA", "Fk": "CAR_FUKUOKA"}


def main():
    d = open(sys.argv[1], "rb").read()

    def off(v):
        if 0x9734000 <= v < 0x9734000 + 0xb8494:
            return v - 0x9734000 + 0x16ec000
        if 0x8048000 <= v < 0x8048000 + 0x16ebfb0:
            return v - 0x8048000
        return None

    names = []
    while True:
        o = off(struct.unpack_from("<I", d, off(NAMES) + 4 * len(names))[0])
        if o is None:
            break
        names.append(d[o:d.index(b"\0", o)].decode("latin1"))
    text = open(sys.argv[2], encoding="cp932", errors="replace").read()
    text = re.sub(r"//[^\n]*", "", text)
    start = {}
    # a block's head names one series or several ("ESeries_110B ESeries_110BExtraUS ..."); the
    # file's first block of a name is the one the loader finds
    for m in re.finditer(r"((?:ESeries_\w+[ \t]*)+)\n\s*RaceField\s+\w+\s+([^\n]*)", text):
        fields = [f.strip() for f in m.group(2).split(",")]
        if len(fields) > 1:
            for n in re.findall(r"ESeries_(\w+)", m.group(1)):
                start.setdefault(n, fields[1])
    rows = []
    for i, n in enumerate(names):
        ramp = start.get(n, "")
        rows.append((CITY.get(ramp[:2], "CAR_TOKYO"), n, ramp))
    out = ["/* Generated by tools/storycity.py from the arcade's ytConfigStory.txt: do not edit. */",
           "#ifndef STORYCITY_H", "#define STORYCITY_H", "",
           "/* by ESeries: the city whose map the story race runs on (its RaceField's start) */",
           "#define STORYCITY_N %d" % len(rows),
           "static const signed char STORYCITY[STORYCITY_N] = {"]
    for city, n, ramp in rows:
        out.append("  %s, /* %s %s */" % (city, n, ramp))
    out += ["};", "", "#endif", ""]
    here = os.path.dirname(os.path.abspath(__file__))
    open(os.path.join(here, "..", "src", "storycity.h"), "w").write("\n".join(out))
    print(len(rows), "series,", sum(1 for r in rows if r[0] != "CAR_TOKYO"), "outside Tokyo")


if __name__ == "__main__":
    main()
