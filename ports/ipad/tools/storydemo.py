"""Read the story's realtime movies' shows (clEffectTable: the titles, the characters' lines,
the fades and sounds over a movie) out of `main` and write src/storydemo.h and
tools/storydemo_texts.txt (the lines, for menupack.py to render).

usage: storydemo.py <main>

clRaceThread::initStory loads table getDemo(period) (src/storymovie.h's demo) when the period
has one (every movie has); clRaceThread::yield then runs clEffectTable::update (0x85dce24) and
draw (0x85db554) each frame. clEffectTable::init (0x85d5f18) takes table t's events from
0x976b7c0 + 8 t {ptr, count}: 12 bytes each {frame, type, arg}, run once the table's frame
counter (+0x1f0, one up an update) reaches their frame. The types (the jump table at
0x93d00f8): 0/1 the picture's colours inverted on/off (clGraphicFrame +0x174), 2/3 its after
image 0.7/0 (+0x17c), 4..7 clMenuFade::setFade (+4) over 1/6 s (0x9771194): 4 from black, 5 to
black, 6 from white, 7 to white; 8 anime row arg (0x976fc00, 24 bytes: cluster, x, y, anime
id, start, length) played once; 9 its cluster stopped; 10 clCutinDisp::setSpeak with the flash,
cut-in row arg; 11 setEnd(row arg's place); 15 SE row arg (0x976fae0, 12 bytes: emOneshotType,
frequency, volume; -1 the one-shot table's own); 20/21 the movie held / let go (+0x1e0:
clRaceThread::race stops its time and draws on clGraphicFreezeCallback, the picture stands).

The cut-in rows, 0x97fc1a0 (28 bytes: ePos, eChar, expression, way, flash, wchar_t string, x),
are set by the static initializer at 0x85d6142: movl $imm, row field / basic_string(wchar_t
const*) on the string field.
"""
import os
import struct
import sys

here = os.path.dirname(os.path.abspath(__file__))
d = open(sys.argv[1], "rb").read()
phoff, = struct.unpack_from("<I", d, 28)
phentsize, phnum = struct.unpack_from("<HH", d, 42)
segs = []
for i in range(phnum):
    t, off, va, _, fsz, _, _, _ = struct.unpack_from("<8I", d, phoff + i * phentsize)
    if t == 1:
        segs.append((va, off, fsz))


def off(va):
    for v, o, n in segs:
        if v <= va < v + n:
            return o + va - v
    raise ValueError(hex(va))


def u32(va):
    return struct.unpack_from("<I", d, off(va))[0]


def cstr(va):
    o = off(va)
    return d[o:d.index(b"\0", o)].decode()


def wstr(va):
    o, s = off(va), ""
    while True:
        c, = struct.unpack_from("<I", d, o)
        if not c:
            return s
        s += chr(c)
        o += 4


TABLES, N_TABLES = 0x976B7C0, 127
ANIME_ROWS, SE_ROWS, CUTIN_ROWS = 0x976FC00, 0x976FAE0, 0x97FC1A0
CUTIN_INIT, CUTIN_N = 0x85D6142, 221
ANIME_FILES = 0x954FB60  # 8 bytes an anime: path
ONESHOTS = 0x931EE08     # nsAudio's one-shots, 20 bytes: path, volume, ...
USED = {0, 1, 4, 5, 6, 7, 8, 9, 10, 11, 15, 20, 21}

tables, events = [], []
for t in range(N_TABLES):
    p, n = u32(TABLES + 8 * t), u32(TABLES + 8 * t + 4)
    tables.append((len(events), n))
    for k in range(n):
        f, ty, a = struct.unpack_from("<iii", d, off(p) + 12 * k)
        events.append((f, ty, a))
types = {e[1] for e in events}
print("event types", sorted(types), "(left out:", sorted(types - USED), ")")

n_anime = max(a for _, ty, a in events if ty in (8, 9)) + 1
animes = []
for r in range(n_anime):
    cl, x, y, aid, start, length = struct.unpack_from("<6i", d, off(ANIME_ROWS + 24 * r))
    assert start == 0 and length == 0, (r, start, length)
    name = os.path.basename(cstr(u32(ANIME_FILES + 8 * aid)))[:-4]
    animes.append((cl, x, y, name))

n_se = max(a for _, ty, a in events if ty == 15) + 1
ses = []
for r in range(n_se):
    kind, _, vol = struct.unpack_from("<iif", d, off(SE_ROWS + 12 * r))
    path = cstr(u32(ONESHOTS + 20 * kind))
    own, = struct.unpack_from("<f", d, off(ONESHOTS + 20 * kind + 4))
    ses.append((os.path.basename(path)[:-4], vol if vol > 0 else own))

# the cut-in rows from their initializer's code
rows = [[0, 0, 0, 0, 0, None, 0] for _ in range(CUTIN_N)]
end = CUTIN_ROWS + 28 * CUTIN_N
o, stop = off(CUTIN_INIT), off(CUTIN_INIT) + 0x8000
arg4 = None
while o < stop:
    if d[o] == 0xC7 and d[o + 1] == 0x05:  # movl $imm, abs
        a, v = struct.unpack_from("<Ii", d, o + 2)
        if CUTIN_ROWS <= a < end and (a - CUTIN_ROWS) % 28 != 20:
            rows[(a - CUTIN_ROWS) // 28][[0, 1, 2, 3, 4, None, 6][(a - CUTIN_ROWS) % 28 // 4]] = v
        o += 10
    elif d[o:o + 4] == b"\xc7\x44\x24\x04":  # movl $imm, 0x4(%esp)
        arg4, = struct.unpack_from("<I", d, o + 4)
        o += 8
    elif d[o:o + 3] == b"\xc7\x04\x24":  # movl $imm, (%esp)
        a, = struct.unpack_from("<I", d, o + 3)
        if CUTIN_ROWS <= a < end and (a - CUTIN_ROWS) % 28 == 20:
            rows[(a - CUTIN_ROWS) // 28][5] = wstr(arg4)
        o += 7
    else:
        o += 1
missing = [k for k, r in enumerate(rows) if r[5] is None]
assert not missing, missing

out = ["/* Generated by tools/storydemo.py from the arcade's clEffectTable: do not edit. */",
       "#ifndef STORYDEMO_H", "#define STORYDEMO_H", "",
       "/* a show's event: at its frame, the type (clEffectTable::update's) with its row */",
       "typedef struct { short frame; unsigned char type, arg; } storydemo_event;",
       "typedef struct { unsigned short first, n; } storydemo_table;",
       "/* an anime row: its cluster, where (640x480), the anime played once */",
       "typedef struct { int cluster, x, y; const char *anim; } storydemo_anime;",
       "/* a cut-in row: its place (nsCutinDisp::ePos), way (the line's side: 0 cons_g_cutin_serifu,",
       " * 1 cons_g_cutin2_serifu), flash (0 cons_g_cutin_effect, 1 cons_g_cutin2_effect) and x; the",
       " * line and the face are menu.bin's DEMO_TEXT / DEMO_FACE + the row */",
       "typedef struct { unsigned char pos, way, flash; short x; } storydemo_cutin;",
       "/* an SE row: the sound (data/sound/<wav>.wav) and its nsAudio volume */",
       "typedef struct { const char *wav; float vol; } storydemo_se;", "",
       "#define STORYDEMO_TABLES %d" % len(tables),
       "static const storydemo_table STORYDEMO_TABLE[STORYDEMO_TABLES] = {"]
out += ["  { %d, %d }," % t for t in tables]
out += ["};", "static const storydemo_event STORYDEMO_EVENT[%d] = {" % len(events)]
out += ["  { %d, %d, %d }," % e for e in events]
out += ["};", "#define STORYDEMO_ANIMES %d" % len(animes),
        "static const storydemo_anime STORYDEMO_ANIME[STORYDEMO_ANIMES] = {"]
out += ['  { %d, %d, %d, "%s" },' % a for a in animes]
out += ["};", "#define STORYDEMO_CUTINS %d" % len(rows),
        "static const storydemo_cutin STORYDEMO_CUTIN[STORYDEMO_CUTINS] = {"]
out += ["  { %d, %d, %d, %d }," % (r[0], r[3], r[4], r[6]) for r in rows]
out += ["};", "#define STORYDEMO_SES %d" % len(ses),
        "static const storydemo_se STORYDEMO_SE[STORYDEMO_SES] = {"]
out += ['  { "%s", %.2ff },' % s for s in ses]
out += ["};", "", "#endif", ""]
open(os.path.join(here, "..", "src", "storydemo.h"), "w").write("\n".join(out))

# the lines for menupack.py: eChar, expression, the text (new lines as \n)
with open(os.path.join(here, "storydemo_texts.txt"), "w", encoding="utf-8") as f:
    for r in rows:
        f.write("%d\t%d\t%s\n" % (r[1], r[2], r[5].replace("\n", "\\n")))
print(len(tables), "tables,", len(events), "events,", len(animes), "animes,", len(rows), "lines,", len(ses), "sounds")
print("animes used:", sorted({a[3] for a in animes}))
