"""Read the story's realtime movies out of `main` (clEffStoryType's periods) and write
src/storymovie.h.

usage: storymovie.py <main>   (WMMT_MAIN for tools/recomp/x86emu.py)

A story select (src/rivaldb.h's select) runs up to 5 periods (clRaceThread::initStory): each a
race (isRace 0x857dde4) or a realtime movie (getRtMovie 0x857d854: its row of
data/rtmovie/table/MovieTableData.txt; 301 = none), the cars in it getECarType(period, 0..2)
0x857e08c (clMovieSystem::Init's rivals), its show over it (hasDemo 0x857d3f0, getDemo
0x857d354: clEffectTable's table, src/storydemo.h), and how clRaceThread::race fades it out 20 frames
before its end (getFade 0x857d1f0: clFader::setFade to 1 in 1/3 s, 1 black, 2 white, 0 none:
clFader::draw's sprite 0x931adfc[!black], 839 atract_p_black / 82 Full_white). A race period
fades out the same way at its Suspend (clRaceThread::race, play state 10) and clRaceThread::run
fades the next period in from it (setFade(0, 1, 1/3)). The port plays the movies before each race.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "recomp"))
os.environ["WMMT_MAIN"] = sys.argv[1]
from x86emu import Emu  # noqa: E402

NONE = 301
e = Emu(trace_unknown=False)
obj = e.alloc(0x40)
rows = []
race_fades = []  # each select's races' getFade, in order
for sel in range(200):
    if not 0 < e.u32(0x973a5c0 + 0x158 * sel) < 400:
        break
    e.w32(obj, sel)
    race = 0
    race_fades.append([])
    for p in range(5):
        is_race = e.call(0x857dde4, obj, p) & 0xff
        mv = e.call(0x857d854, obj, p)
        if is_race:
            race += 1
            race_fades[-1].append(e.call(0x857d1f0, obj, p))
            continue
        if mv == NONE:
            continue
        cars = [e.call(0x857e08c, obj, p, k) for k in range(3)]
        demo = e.call(0x857d354, obj, p) if e.call(0x857d3f0, obj, p) & 0xff else -1
        rows.append((sel, race, mv, cars, e.call(0x857d1f0, obj, p), demo))
out = ["/* Generated by tools/storymovie.py from the arcade's story periods: do not edit. */",
       "#ifndef STORYMOVIE_H", "#define STORYMOVIE_H", "",
       "/* a realtime movie of a story select, played before its race `race` (0 the first; the",
       " * select's races are src/rivaldb.h's), with the cars it shows (ECarType, 0 none) */",
       "typedef struct {",
       "  int select, race;",
       "  int movie;   /* data/rtmovie/table/MovieTableData.txt's row */",
       "  int cars[3];",
       "  int fade;    /* its last 20 frames: 1 to black, 2 to white, 0 none */",
       "  int demo;    /* the show over it: src/storydemo.h's table (-1 none) */",
       "} storymovie;", "",
       "#define STORYMOVIE_N %d" % len(rows),
       "static const storymovie STORYMOVIE[STORYMOVIE_N] = {"]
for r in rows:
    out.append("  { %d, %d, %d, { %d, %d, %d }, %d, %d }," % (r[0], r[1], r[2], *r[3], r[4], r[5]))
out += ["};", "",
        "/* how a select's race `race` fades out at its end when the select goes on (Suspend), as the",
        " * movies' fade; the next period fades in from it */",
        "#define STORYRACE_SELECTS %d" % len(race_fades),
        "static const unsigned char STORYRACE_FADE[STORYRACE_SELECTS][5] = {"]
out += ["  { %s }," % ", ".join(str(f) for f in (fs + [0] * 5)[:5]) for fs in race_fades]
out += ["};", "", "#endif", ""]
here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, "..", "src", "storymovie.h"), "w").write("\n".join(out))
print(len(rows), "movies;", rows[:6])
