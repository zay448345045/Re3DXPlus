"""Read the story's tuning screen (seqStTune 0x8833f24, clSeqStTuneThread) tables out of
`main` and write src/sttune.h and tools/sttune_texts.txt.

usage: sttune.py <main>

- seqStTune: the car's flags from its car id (CarIDGetFromModelID(card model, 1)): the
  NA cars (0x29, 0x17, 0x1a, 1, 2, 6, 0x23, 0x2c, 0x2d, 0, 0x34, 0x32, 0x30, 0x2e, 0x37: a
  turbo kit first), 0x24 (an engine swap first), the VIP cars (0x34, 0x29: Gatchan's rows),
  get_car_model_data(model)+0x28 in {1, 2} (the second power part is the engine swap's
  picture), the tuner of steps 21..30 (the jump table at 0x93fc830) and of 31..
  (0xe VIP, 0x10 the Z31, else 0xd).
- clSeqStTuneThread::clMenuLayout: 28-byte rows {tuner, parts picture, parts name, three
  lines, shop} by value for steps 1..20: handling 0x93fc264 (VIP 0x93fc384), power
  0x93fc4a4 (VIP 0x93fc604, the NA cars' first 0x93fc5f4, 0x24's first 0x93fc5d8); steps
  21..30 the part's name (0x9773960, VIP 0x9773920) and picture (0x93fc200, VIP 0x93fc240)
  by step and the tuner's lines (12-byte rows) by step; 31.. the tuner's lines only. The
  tuners {name, portrait, shop, top bar message} at 0x93fc0e0. Rikako's balance warning
  (0x9773988, 0x977398c).
The texts (clSpriteFont, font 1) are pre-rendered by menupack.py as STTUNE_TEXT + k.
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from cardb import Main  # noqa: E402

TEXT_BASE = 101300
m = Main(sys.argv[1])


def u(a):
    return m.r32(a)


def ws(a):
    if a == 0:
        return ""
    s = []
    while True:
        c = u(a)
        if c == 0:
            return "".join(s)
        s.append(chr(c))
        a += 4


texts = []


def text(s):
    """the pre-rendered text's index (-1: none)"""
    if not s:
        return -1
    if s not in texts:
        texts.append(s)
    return texts.index(s)


def row(a):
    c, p, n, l1, l2, l3, shop = [u(a + 4 * i) for i in range(7)]
    return (c, p, text(ws(n)), text(ws(l1)), text(ws(l2)), text(ws(l3)))


def rows(a, n):
    """by value; row 0 is never read (and holds the table before's tail)"""
    return [(0, 1, -1, -1, -1, -1)] + [row(a + 28 * i) for i in range(1, n)]


def lines(a, n):
    return [tuple(text(ws(u(a + 12 * i + 4 * j))) for j in range(3)) for i in range(n)]


hand, hand_vip = rows(0x93FC264, 11), rows(0x93FC384, 11)
power, power_vip = rows(0x93FC4A4, 12), rows(0x93FC604, 11)
power_na, power_24 = row(0x93FC5F4), row(0x93FC5D8)
charas = [tuple(u(0x93FC0E0 + 16 * k + 4 * j) for j in range(4)) for k in range(18)]
mid_name = [[text(ws(u(a + 4 * i))) for i in range(10)] for a in (0x9773960, 0x9773920)]
mid_parts = [[u(a + 4 * i) for i in range(10)] for a in (0x93FC200, 0x93FC240)]
MID_LINES = {1: 0x9773820, 2: 0x97738A0, 7: 0x9773520, 8: 0x97735A0, 9: 0x97737A0, 10: 0x9773720,
             11: 0x97736A0, 12: 0x9773620, 15: 0x97734A0}
mid_lines = {c: lines(a, 10) for c, a in MID_LINES.items()}
TOP_LINES = {13: 0x9773460, 14: 0x9773420, 16: 0x97733E0}
top_lines = {c: lines(a, 4) for c, a in TOP_LINES.items()}
get = []
for c in range(18):
    m.call(0x88DBF88, c)
    get.append(m.r32(0x97FF7D0))
warn = (text(ws(u(0x9773988))), text(ws(u(0x977398C))))
# the step line: ＳＴＥＰ and the step's full-width number, then "：" and the part's name
step = ws(0x933A5DC)
colon = ws(0x93F0EE4)
steps = [text(step + "".join(chr(0xFF10 + int(d)) for d in str(n))) for n in range(1, 36)]
part_names = sorted({r[2] for r in hand + hand_vip + power + power_vip + [power_na, power_24]} | set(mid_name[0]) | set(mid_name[1]))
colon_names = {k: text(colon + texts[k]) for k in part_names if k >= 0}

# the cars' flags, by the car select's cars (tools/cars.json)
import json  # noqa: E402
NA = {0x29, 0x17, 0x1A, 1, 2, 6, 0x23, 0x2C, 0x2D, 0, 0x34, 0x32, 0x30, 0x2E, 0x37}
jt = {}
for c in range(0x38):
    t = u(0x93FC830 + 4 * c) & 0xFFFFFFFF
    jt[c] = t
# each jump table target's first instruction is mov $tuner, %eax (b8 imm32)
def tuner20(c):
    t = jt[c]
    op = bytes(m.mu.mem_read(t, 5))
    assert op[0] == 0xB8, hex(t)
    return struct.unpack_from("<i", op, 1)[0]


cars = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "cars.json")))
flags = []
for mk in cars["makers"]:
    row_ = []
    for car in mk["cars"]:
        cid = m.call(0x893DD48, car["colors"][0]["model"], 1)
        model = m.call(0x893CF98, cid, 1)
        k28 = m.r32(m.call(0x88DC0C8, model) + 0x28)
        vip = cid in (0x34, 0x29)
        row_.append(dict(cid=cid, na=cid in NA, e24=cid == 0x24, vip=vip, k28=k28 in (1, 2),
                         t20=tuner20(cid) if cid <= 0x37 else 2, t30=0xE if vip else 0x10 if cid == 0x19 else 0xD,
                         label=car["label"]))
    flags.append(row_)

out = ["/* Generated by tools/sttune.py from the arcade's story tuning screen (seqStTune): do not edit. */",
       "#ifndef STTUNE_H", "#define STTUNE_H", "",
       "#define STTUNE_TEXT %d /* the pre-rendered texts: STTUNE_TEXT + k (menupack.py) */" % TEXT_BASE,
       "", "/* a row: the tuner, the part's picture (1 none), its name, the three lines (texts, -1 none) */",
       "typedef struct { short chara, parts, name, line[3]; } sttune_row;",
       "/* the tuners (0x93fc0e0): name, portrait, shop (1 none), top bar message (0 none) */",
       "static const short STTUNE_CHARA[18][4] = {"]
out += ["  { %d, %d, %d, %d }," % c for c in charas]
out += ["};", ""]


def emit_rows(name, rs, comment):
    out.append("/* %s */" % comment)
    out.append("static const sttune_row %s[%d] = {" % (name, len(rs)))
    out.extend("  { %d, %d, %d, { %d, %d, %d } }," % r for r in rs)
    out.append("};")


emit_rows("STTUNE_HAND", hand, "steps 1..20, handling, by the new value (0x93fc264)")
emit_rows("STTUNE_HAND_VIP", hand_vip, "the VIP cars' (0x93fc384)")
emit_rows("STTUNE_POWER", power, "power, by the new value (0x93fc4a4)")
emit_rows("STTUNE_POWER_VIP", power_vip, "the VIP cars' (0x93fc604)")
out.append("static const sttune_row STTUNE_POWER_NA = { %d, %d, %d, { %d, %d, %d } }; /* the NA cars' first (0x93fc5f4) */" % power_na)
out.append("static const sttune_row STTUNE_POWER_24 = { %d, %d, %d, { %d, %d, %d } }; /* car 0x24's first (0x93fc5d8) */" % power_24)
out += ["", "/* steps 21..30 by step: the part's name and picture, plain and VIP */",
        "static const short STTUNE_MID_NAME[2][10] = {"]
out += ["  { %s }," % ", ".join(map(str, r)) for r in mid_name]
out += ["};", "static const short STTUNE_MID_PARTS[2][10] = {"]
out += ["  { %s }," % ", ".join(map(str, r)) for r in mid_parts]
out += ["};", "/* the tuners' lines, steps 21..30 (an unlisted tuner has Ohta's) */",
        "static const short STTUNE_MID_LINES[17][10][3] = {"]
for c in range(17):
    ls = mid_lines.get(c)
    out.append("  { %s }," % ", ".join("{ %d, %d, %d }" % l for l in ls) if ls else "  { { 0 } }, /* %d */" % c)
out += ["};", "static const unsigned char STTUNE_MID_HAS[17] = { %s };" % ", ".join("1" if c in mid_lines else "0" for c in range(17)),
        "/* steps 31..34 by step, tuners 13, 14 and 16 */",
        "static const short STTUNE_TOP_LINES[17][4][3] = {"]
for c in range(17):
    ls = top_lines.get(c)
    out.append("  { %s }," % ", ".join("{ %d, %d, %d }" % l for l in ls) if ls else "  { { 0 } }, /* %d */" % c)
out += ["};",
        "/* the race result's tuning message by tuner (get_tuner_data 0x88dbf88: menu_p_finish_result_st_get_*) */",
        "static const short STTUNE_GET[18] = { %s };" % ", ".join(str(g) for g in get),
        "/* Rikako's balance warning: more power than handling, less */",
        "static const short STTUNE_WARN[2] = { %d, %d };" % warn,
        "/* ＳＴＥＰn by step 1..35, and \"：name\" by the name's text */",
        "static const short STTUNE_STEP[35] = { %s };" % ", ".join(map(str, steps)),
        "static const short STTUNE_COLON[%d] = { %s };" % (len(texts) + 1, ", ".join(
            str(colon_names.get(k, -1)) for k in range(len(texts) + 1))),
        "",
        "/* by the car select's cars (src/cardb.h): an NA car (a turbo kit first), car 0x24 (an engine",
        " * swap first), a VIP car, the engine swap's picture second, the tuner of steps 21..30 and 31.. */",
        "typedef struct { unsigned char na, e24, vip, k28, t20, t30; } sttune_car;",
        "static const sttune_car STTUNE_CAR[%d][%d] = {" % (len(flags), max(len(r) for r in flags))]
for r in flags:
    out.append("  { %s }," % ", ".join("{ %d, %d, %d, %d, %d, %d }" % (f["na"], f["e24"], f["vip"], f["k28"], f["t20"], f["t30"]) for f in r))
out += ["};", "", "#endif", ""]
here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, "..", "src", "sttune.h"), "w").write("\n".join(out))
open(os.path.join(here, "sttune_texts.txt"), "w", encoding="utf-8").write("".join("1\t%s\n" % t for t in texts))
for r in flags:
    for f in r:
        print("%3d %-45s na%d e24%d vip%d k28%d t20=%d t30=%d" % (f["cid"], f["label"], f["na"], f["e24"], f["vip"], f["k28"], f["t20"], f["t30"]))
print(len(texts), "texts")
